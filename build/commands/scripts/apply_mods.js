// Simplified script to apply Luxxle modifications to Chromium source
// without git operations - just file copying and branding updates

const fs = require('fs-extra')
const path = require('path')
const config = require('../lib/config')
const util = require('../lib/util')
const Log = require('../lib/logging')
const l10nUtil = require('../lib/l10nUtil')
const crypto = require('crypto')

// Initialize config
config.update({})

const calculateFileChecksum = (filename) => {
  // adapted from https://github.com/kodie/md5-file
  const BUFFER_SIZE = 8192
  const fd = fs.openSync(filename, 'r')
  const buffer = Buffer.alloc(BUFFER_SIZE)
  const md5 = crypto.createHash('md5')

  try {
    let bytesRead
    do {
      bytesRead = fs.readSync(fd, buffer, 0, BUFFER_SIZE)
      md5.update(buffer.slice(0, bytesRead))
    } while (bytesRead === BUFFER_SIZE)
  } finally {
    fs.closeSync(fd)
  }

  return md5.digest('hex')
}

const walkSync = (dir) => {
  const files = []
  const list = fs.readdirSync(dir)
  list.forEach((file) => {
    const filePath = path.join(dir, file)
    const stat = fs.statSync(filePath)
    if (stat && stat.isDirectory()) {
      files.push(...walkSync(filePath))
    } else {
      files.push(filePath)
    }
  })
  return files
}

function applyLuxxleMods() {
  Log.progressStart('apply luxxle modifications')
  
  const chromeComponentsDir = path.join(config.srcDir, 'components')
  const luxxleComponentsDir = path.join(config.luxxleCoreDir, 'components')
  const chromeAppDir = path.join(config.srcDir, 'chrome', 'app')
  const luxxleAppDir = path.join(config.luxxleCoreDir, 'app')
  const chromeBrowserResourcesDir = path.join(
    config.srcDir,
    'chrome',
    'browser',
    'resources',
  )
  const luxxleBrowserResourcesDir = path.join(
    config.luxxleCoreDir,
    'browser',
    'resources',
  )

  let fileMap = new Set()
  const autoGeneratedLuxxleToChromiumMapping = Object.assign(
    {},
    l10nUtil.getAutoGeneratedLuxxleToChromiumMapping(),
  )
  
  // The key mappings for string files
  autoGeneratedLuxxleToChromiumMapping[
    path.join(luxxleAppDir, 'luxxle_strings.grd')
  ] = path.join(chromeAppDir, 'luxxle_strings.grd')
  autoGeneratedLuxxleToChromiumMapping[
    path.join(luxxleAppDir, 'settings_luxxle_strings.grdp')
  ] = path.join(chromeAppDir, 'settings_luxxle_strings.grdp')
  autoGeneratedLuxxleToChromiumMapping[
    path.join(luxxleComponentsDir, 'components_luxxle_strings.grd')
  ] = path.join(chromeComponentsDir, 'components_luxxle_strings.grd')

  Object.entries(autoGeneratedLuxxleToChromiumMapping).forEach((mapping) =>
    fileMap.add(mapping),
  )

  // Copy xtb files for translations
  fileMap.add([
    path.join(luxxleAppDir, 'resources'),
    path.join(chromeAppDir, 'resources'),
  ])
  fileMap.add([
    path.join(luxxleComponentsDir, 'strings'),
    path.join(chromeComponentsDir, 'strings'),
  ])

  // Copy theme and branding files
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'luxxle'),
  ])
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'chromium'),
  ])
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'default_100_percent', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'default_100_percent', 'luxxle'),
  ])
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'default_200_percent', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'default_200_percent', 'luxxle'),
  ])
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'default_100_percent', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'default_100_percent', 'chromium'),
  ])
  fileMap.add([
    path.join(luxxleAppDir, 'theme', 'default_200_percent', 'luxxle'),
    path.join(chromeAppDir, 'theme', 'default_200_percent', 'chromium'),
  ])

  // Copy component resources
  fileMap.add([
    path.join(luxxleComponentsDir, 'resources', 'default_100_percent'),
    path.join(chromeComponentsDir, 'resources', 'default_100_percent'),
  ])
  fileMap.add([
    path.join(
      luxxleComponentsDir,
      'resources',
      'default_100_percent',
      'luxxle',
    ),
    path.join(
      chromeComponentsDir,
      'resources',
      'default_100_percent',
      'chromium',
    ),
  ])
  fileMap.add([
    path.join(luxxleComponentsDir, 'resources', 'default_200_percent'),
    path.join(chromeComponentsDir, 'resources', 'default_200_percent'),
  ])
  fileMap.add([
    path.join(
      luxxleComponentsDir,
      'resources',
      'default_200_percent',
      'luxxle',
    ),
    path.join(
      chromeComponentsDir,
      'resources',
      'default_200_percent',
      'chromium',
    ),
  ])

  // Copy vector icons
  fileMap.add([
    path.join(luxxleComponentsDir, 'vector_icons', 'luxxle'),
    path.join(chromeComponentsDir, 'vector_icons', 'luxxle'),
  ])

  // Copy browser resources
  fileMap.add([
    path.join(luxxleBrowserResourcesDir, 'chrome-logo-faded.png'),
    path.join(chromeBrowserResourcesDir, 'chrome-logo-faded.png'),
  ])

  console.log('Copying Luxxle files to Chromium source...')

  for (const [source, output] of fileMap) {
    if (!fs.existsSync(source)) {
      console.warn(
        `Warning: Source not found: ${source}`,
      )
      continue
    }

    let sourceFiles = []

    // get all the files if source is a directory
    if (fs.statSync(source).isDirectory()) {
      sourceFiles = walkSync(source)
    } else {
      sourceFiles = [source]
    }

    for (let sourceFile of sourceFiles) {
      const destinationFile = path.join(
        output,
        path.relative(source, sourceFile),
      )
      
      if (
        !fs.existsSync(destinationFile) ||
        calculateFileChecksum(sourceFile) !==
          calculateFileChecksum(destinationFile)
      ) {
        fs.copySync(sourceFile, destinationFile)
        console.log(sourceFile + ' copied to ' + destinationFile)
      }
    }
  }

  Log.progressFinish('apply luxxle modifications')
  console.log('✅ Luxxle modifications applied successfully!')
}

// Run the function
try {
  applyLuxxleMods()
} catch (error) {
  console.error('❌ Error applying Luxxle modifications:', error)
  process.exit(1)
}